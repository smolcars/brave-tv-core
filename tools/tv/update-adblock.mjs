import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { uBlockResources } from 'adblock-rs';
import { preprocess } from './filter-preprocessor.mjs';

const resourcesRevision = '6da9b247c3368baa8b4f24cd02046e18702a6527';
const mirrorRevision = 'fe247f620abf31578682bf0aad8f90cd29a52ffb';
const ublockRevision = '4dfbb048607ec4fd19c1c252fd255df6cc653720';
if (!process.argv[2]) throw new Error('Pass the clean pinned brave/uBlock checkout path.');
const ublock = resolve(process.argv[2]);
const git = (...args) => execFileSync('git', ['-C', ublock, ...args], { encoding: 'utf8' }).trim();
if (git('rev-parse', 'HEAD') !== ublockRevision || git('status', '--porcelain')) {
  throw new Error(`uBlock must be clean at ${ublockRevision}`);
}
const destination = new URL('../../components/brave_shields/resources/bundled/', import.meta.url);
const provenance = { resourcesRevision, mirrorRevision, ublockRevision, sources: [], files: {} };
const sha256 = data => createHash('sha256').update(data).digest('hex');

async function download(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  const data = await response.text();
  if (!data.trim() || data.length > 20_000_000 || /^\s*<!doctype html/i.test(data)) {
    throw new Error(`Invalid filter payload: ${url}`);
  }
  return data;
}

async function save(name, data) {
  await writeFile(new URL(name, destination), data);
  provenance.files[name] = sha256(data);
}

const resourcesRoot = `https://raw.githubusercontent.com/brave/adblock-resources/${resourcesRevision}`;
const catalog = JSON.parse(await download(`${resourcesRoot}/filter_lists/list_catalog.json`))
  .filter(entry => entry.default_enabled && (!entry.platforms || entry.platforms.includes('ANDROID')));
if (catalog.length !== 5) throw new Error('Review changes to the default catalog before updating.');

// Finish every download before replacing a previously working bundle.
const outputs = [];
for (const entry of catalog) {
  const parts = [];
  for (const source of entry.sources) {
    if (source.format !== 'Standard') throw new Error(`Unsupported format: ${source.format}`);
    const hash = createHash('md5').update(source.url).digest('hex');
    const mirror = `https://raw.githubusercontent.com/brave/adblock-lists-mirror/${mirrorRevision}/lists/${hash}.txt`;
    const raw = await download(mirror);
    const title = source.title || entry.title;
    let data = preprocess({ title, data: raw }).data;
    // Match the upstream packager's restriction on Brave-only scriptlet directives.
    if (!title.startsWith('Brave ') && title !== 'Experimental ad blocker') {
      data = data.split('\n').filter(line => !line.includes('+js(brave-')).join('\n');
    }
    parts.push(`! Source: ${source.url}\n${data}`);
    provenance.sources.push({ url: source.url, mirror, sha256: sha256(raw) });
  }
  outputs.push([`${entry.list_text_component.component_id}.txt`, parts.join('\n') + '\n']);
}
const braveResources = JSON.parse(await download(`${resourcesRoot}/dist/resources.json`));
if (!Array.isArray(braveResources)) throw new Error('Invalid resources');
const { builtinScriptlets } = await import(pathToFileURL(join(ublock, 'src/js/resources/scriptlets.js')));
const names = new Set(builtinScriptlets.map(scriptlet => scriptlet.name));
for (const scriptlet of builtinScriptlets) {
  for (const dependency of scriptlet.dependencies ?? []) {
    if (!names.has(dependency)) throw new Error(`Missing scriptlet dependency: ${dependency}`);
  }
}
const redirects = uBlockResources(join(ublock, 'src/web_accessible_resources'),
  join(ublock, 'src/js/redirect-resources.js')).filter(resource => resource.name !== 'google-ima-dai.js');
const scriptlets = builtinScriptlets.map(scriptlet => ({
  name: scriptlet.name,
  aliases: scriptlet.aliases ?? [],
  kind: { mime: 'application/javascript' },
  content: Buffer.from(scriptlet.fn.toString()).toString('base64'),
  dependencies: scriptlet.dependencies ?? [],
  permission: scriptlet.requiresTrust ? 1 : 0,
}));
const resources = JSON.stringify([...redirects, ...braveResources, ...scriptlets]);
await mkdir(destination, { recursive: true });
for (const [name, data] of outputs) await save(name, data);
await save('catalog.json', JSON.stringify(catalog, null, 2) + '\n');
await save('resources.json', resources);
provenance.version = sha256(JSON.stringify(provenance.files));
await writeFile(new URL('version.h', destination),
  `// Generated by tools/tv/update-adblock.mjs.\n` +
  `#ifndef BRAVE_COMPONENTS_BRAVE_SHIELDS_RESOURCES_BUNDLED_VERSION_H_\n` +
  `#define BRAVE_COMPONENTS_BRAVE_SHIELDS_RESOURCES_BUNDLED_VERSION_H_\n` +
  `namespace brave_shields {\n` +
  `inline constexpr char kAdBlockBundleVersion[] = "Brave-TV adblock ${provenance.version}\\n";\n` +
  `inline constexpr char kAdBlockBundleCatalogHash[] = "${provenance.files['catalog.json']}";\n` +
  `}\n#endif\n`);
await writeFile(new URL('provenance.json', destination), JSON.stringify(provenance, null, 2) + '\n');
console.log(`Saved ${catalog.length} default filter groups to ${fileURLToPath(destination)}`);
